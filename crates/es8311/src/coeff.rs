//! Clock divider coefficients for slave mode with an external MCLK.
//!
//! Ported from the `coeff_div` table in Espressif `esp_codec_dev` `device/es8311/es8311.c`
//! (Apache-2.0, see THIRD_PARTY_NOTICES.md). One row per (MCLK, sample rate) pair.

/// One row of the clock table.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Coeff {
    /// MCLK frequency in Hz.
    pub mclk: u32,
    /// Sample rate in Hz.
    pub rate: u32,
    /// Pre-divider, 1..=8.
    pub pre_div: u8,
    /// Pre-multiplier: 1, 2, 4 or 8.
    pub pre_multi: u8,
    /// ADC clock divider.
    pub adc_div: u8,
    /// DAC clock divider.
    pub dac_div: u8,
    /// 0 = single speed, 1 = double speed.
    pub fs_mode: u8,
    /// LRCK divider high bits.
    pub lrck_h: u8,
    /// LRCK divider low bits.
    pub lrck_l: u8,
    /// BCLK divider.
    pub bclk_div: u8,
    /// ADC oversampling rate.
    pub adc_osr: u8,
    /// DAC oversampling rate.
    pub dac_osr: u8,
}

#[allow(clippy::too_many_arguments)]
const fn c(
    mclk: u32,
    rate: u32,
    pre_div: u8,
    pre_multi: u8,
    adc_div: u8,
    dac_div: u8,
    fs_mode: u8,
    lrck_h: u8,
    lrck_l: u8,
    bclk_div: u8,
    adc_osr: u8,
    dac_osr: u8,
) -> Coeff {
    Coeff {
        mclk,
        rate,
        pre_div,
        pre_multi,
        adc_div,
        dac_div,
        fs_mode,
        lrck_h,
        lrck_l,
        bclk_div,
        adc_osr,
        dac_osr,
    }
}

